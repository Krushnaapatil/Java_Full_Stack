public class typeCasting {
    static void main() {
        //wideing type casting - implicit
        int a = 100;
        double b = a;
        //wideing type casting - explicit
        int aa = 100;
        double bb = (double) a;

        //narrowing type casting - implicit
        double c = 300.45;
        int d = (int)c;


    }
}
